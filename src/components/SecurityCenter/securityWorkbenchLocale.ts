const getLocaleValue = () => {
  if (i18n.global.locale && typeof i18n.global.locale === 'object' && 'value' in i18n.global.locale) {
    return String(i18n.global.locale.value || '')
  }
  return 'en'
}

export const getWorkbenchLocale = (): WorkbenchLocale =>
  getLocaleValue().startsWith('zh') ? 'zh' : 'en'

export const isWorkbenchChinese = () => getWorkbenchLocale() === 'zh'

const resolveMessage = (source: WorkbenchMessages, path: string): string | undefined => {
  const segments = path.split('.')
  let current: string | WorkbenchMessages | undefined = source
  for (const segment of segments) {
    if (!current || typeof current === 'string') return undefined
    current = current[segment]
  }
  return typeof current === 'string' ? current : undefined
}

export const wb = (
  path: string,
  params: Record<string, string | number | boolean | null | undefined> = {},
) => {
  const locale = getWorkbenchLocale()
  const template = resolveMessage(messages[locale], path) ?? resolveMessage(messages.en, path) ?? path
  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const value = params[key]
    return value == null ? '' : String(value)
  })
}
